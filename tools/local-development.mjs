// Portable SQLite fixture commands. Never connects to an external database.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, openSync, closeSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export function runNpm(args, env) {
  const cli = process.env.npm_execpath ?? join(dirname(process.execPath), "node_modules/npm/bin/npm-cli.js");
  if (!existsSync(cli)) throw new Error("Run this command through npm so npm_execpath is available.");
  const result = spawnSync(process.execPath, [cli, ...args], { stdio: "inherit", env });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.chdir(fileURLToPath(new URL("../", import.meta.url)));
  if (process.env.DATABASE_URL && process.env.DATABASE_URL !== "file:./dev.db") {
    throw new Error("External DATABASE_URL preserved; use a separate fixture environment.");
  }
  const mode = process.argv[2];
  if (!["setup", "dev"].includes(mode)) throw new Error("Expected setup or dev.");
  const env = { ...process.env, DATABASE_URL: "file:./dev.db" };
  if (existsSync(".env")) throw new Error("Existing .env preserved; use a separate fixture environment.");
  if (existsSync(".env.local")) {
    const existing = readFileSync(".env.local", "utf8");
    if (!existing.startsWith("# Generated by Dealmind Codespaces fixture setup\n") || !existing.includes('DATABASE_URL="file:./dev.db"')) {
      throw new Error("Existing .env.local preserved; use the isolated fixture setup.");
    }
  }
  if (mode === "setup" && existsSync("prisma/dev.db")) {
    throw new Error("Existing fixture database preserved. Use dev or review schema changes manually.");
  }
  runNpm(["exec", "--", "prisma", "generate", "--schema", "prisma/schema.sqlite.prisma"], env);
  if (mode === "setup") {
    closeSync(openSync("prisma/dev.db", "wx"));
    runNpm(["exec", "--", "prisma", "db", "push", "--schema", "prisma/schema.sqlite.prisma"], env);
    runNpm(["exec", "--", "tsx", "prisma/seed.ts"], env);
  } else {
    runNpm(["exec", "--", "next", "dev", ...process.argv.slice(3)], env);
  }
}
